def get_session(region: str, local: bool) -> boto3.Session:
    if local:
        print("    [MODE] LocalStack — http://localhost:4566")
        return boto3.Session(
            aws_access_key_id="test",
            aws_secret_access_key="test",
            region_name=region,
        )
    print("    [MODE] Real AWS — ~/.aws/credentials")
    return boto3.Session(region_name=region)


def get_clients(session: boto3.Session, local: bool):
    kwargs = {"endpoint_url": LOCALSTACK_URL} if local else {}
    return (
        session.client('s3',  **kwargs),
        session.client('iam', **kwargs),
        session.client('sts', **kwargs),
    )


def setup_lab(region=REGION, local=False):
    banner()
    session      = get_session(region, local)
    s3, iam, sts = get_clients(session, local)

    print(f"[1/4] Creating S3 bucket: {BUCKET_NAME}")
    try:
        if region == "us-east-1":
            s3.create_bucket(Bucket=BUCKET_NAME)
        else:
            s3.create_bucket(
                Bucket=BUCKET_NAME,
                CreateBucketConfiguration={'LocationConstraint': region}
            )
        s3.put_public_access_block(
            Bucket=BUCKET_NAME,
            PublicAccessBlockConfiguration={
                'BlockPublicAcls': True, 'IgnorePublicAcls': True,
                'BlockPublicPolicy': True, 'RestrictPublicBuckets': True
            }
        )
        print(f"    ✓ Bucket '{BUCKET_NAME}' created")
    except Exception as e:
        if "BucketAlreadyOwnedByYou" in str(e) or "BucketAlreadyExists" in str(e):
            print(f"    ⚠ Bucket already exists — continuing")
        else:
            print(f"    ✗ Error: {e}")
            sys.exit(1)

    print("[2/4] Uploading files...")
    data_dir = Path(__file__).parent / "s3-bucket-contents"
    for f in data_dir.glob("*"):
        if f.is_file():
            s3.upload_file(str(f), BUCKET_NAME, f.name)
            print(f"    ✓ s3://{BUCKET_NAME}/{f.name}")

    print(f"[3/4] Creating IAM User: {IAM_USER}")
    try:
        iam.create_user(UserName=IAM_USER)
        print(f"    ✓ User '{IAM_USER}' created")
    except Exception as e:
        print(f"    ⚠ {e}")

    policy = {
        "Version": "2012-10-17",
        "Statement": [{
            "Sid": "AllowS3ReadAll", "Effect": "Allow",
            "Action": ["s3:GetObject", "s3:ListBucket",
                       "s3:ListAllMyBuckets", "s3:GetBucketLocation"],
            "Resource": "*"
        }]
    }
    iam.put_user_policy(UserName=IAM_USER, PolicyName=IAM_POLICY,
                        PolicyDocument=json.dumps(policy))
    print(f"    ✓ Overly-permissive policy attached")

    print(f"[4/4] Generating Access Keys...")
    resp = iam.create_access_key(UserName=IAM_USER)
    key  = resp['AccessKey']
    creds_path = Path(__file__).parent / "generated_credentials.txt"
    creds_path.write_text(
        f"[{IAM_USER}]\n"
        f"aws_access_key_id     = {key['AccessKeyId']}\n"
        f"aws_secret_access_key = {key['SecretAccessKey']}\n"
        f"region                = {region}\n"
    )
    print(f"    ✓ Key: {key['AccessKeyId']}")
    print(f"    ✓ Saved: {creds_path}")
    print("\n✅ SETUP COMPLETE\n")


def teardown_lab(region=REGION, local=False):
    banner()
    print("⚠  TEARING DOWN LAB...\n")
    session      = get_session(region, local)
    s3, iam, sts = get_clients(session, local)

    try:
        print(f"[1/3] Deleting bucket: {BUCKET_NAME}")
        paginator = s3.get_paginator('list_objects_v2')
        for page in paginator.paginate(Bucket=BUCKET_NAME):
            objs = [{'Key': o['Key']} for o in page.get('Contents', [])]
            if objs:
                s3.delete_objects(Bucket=BUCKET_NAME, Delete={'Objects': objs})
        s3.delete_bucket(Bucket=BUCKET_NAME)
        print(f"    ✓ Bucket deleted")
    except Exception as e:
        print(f"    ⚠ {e}")

    try:
        print(f"[2/3] Cleaning up IAM: {IAM_USER}")
        for k in iam.list_access_keys(UserName=IAM_USER)['AccessKeyMetadata']:
            iam.delete_access_key(UserName=IAM_USER, AccessKeyId=k['AccessKeyId'])
        iam.delete_user_policy(UserName=IAM_USER, PolicyName=IAM_POLICY)
        iam.delete_user(UserName=IAM_USER)
        print(f"    ✓ User deleted")
    except Exception as e:
        print(f"    ⚠ {e}")

    print("[3/3] Cleaning local files...")
    creds = Path(__file__).parent / "generated_credentials.txt"
    if creds.exists():
        creds.unlink()
        print(f"    ✓ Deleted {creds}")
    print("\n✅ TEARDOWN COMPLETE\n")


