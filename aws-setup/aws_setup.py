def setup_sim():
    """
    Tạo toàn bộ môi trường lab ngay trên máy local.
    Giả lập S3 bucket = thư mục, IAM = JSON file, credentials = text file.
    """
    banner()
    print("[SIM MODE] Chạy hoàn toàn local — không cần AWS hay Docker\n")

    # ── Step 1: Tạo "S3 bucket" (= thư mục local) ─────────────
    print(f"[1/4] Tạo S3 bucket giả lập: s3://{BUCKET_NAME}/")
    bucket_dir = SIM_ROOT / "s3" / BUCKET_NAME
    bucket_dir.mkdir(parents=True, exist_ok=True)

    # Metadata giả lập
    meta = {
        "BucketName": BUCKET_NAME,
        "Region": REGION,
        "CreationDate": datetime.now().isoformat(),
        "AccessControl": "private",
        "PublicAccessBlock": {
            "BlockPublicAcls": True,
            "RestrictPublicBuckets": True
        }
    }
    (bucket_dir / "_bucket_meta.json").write_text(json.dumps(meta, indent=2))
    print(f"    ✓ Bucket '{BUCKET_NAME}' created (private)")

    # ── Step 2: Upload sensitive files ────────────────────────
    print("[2/4] Upload file nhạy cảm lên S3 giả lập...")
    data_dir = Path(__file__).parent / "s3-bucket-contents"
    for src in data_dir.glob("*"):
        if src.is_file():
            shutil.copy(src, bucket_dir / src.name)
            size = src.stat().st_size
            print(f"    ✓ s3://{BUCKET_NAME}/{src.name}  ({size} bytes)")

    # ── Step 3: Tạo IAM User ──────────────────────────────────
    print(f"[3/4] Tạo IAM User: {IAM_USER}")
    iam_dir = SIM_ROOT / "iam" / "users" / IAM_USER
    iam_dir.mkdir(parents=True, exist_ok=True)

    # ❌ Overly-permissive policy (intentional misconfiguration)
    policy = {
        "Version": "2012-10-17",
        "Statement": [{
            "Sid": "AllowS3ReadAll",
            "Effect": "Allow",
            "Action": [
                "s3:GetObject",
                "s3:ListBucket",
                "s3:ListAllMyBuckets",   # ← Too broad!
                "s3:GetBucketLocation"
            ],
            "Resource": "*"              # ← Violates Least Privilege!
        }]
    }
    (iam_dir / f"{IAM_POLICY}.json").write_text(json.dumps(policy, indent=2))
    print(f"    ✓ IAM User '{IAM_USER}' created")
    print(f"    ⚠ Policy: s3:* on Resource:* — intentional misconfiguration!")

    # ── Step 4: Generate Access Keys (giả lập) ───────────────
    print(f"[4/4] Tạo Access Keys cho {IAM_USER}...")

    # Key giả lập — format đúng chuẩn AWS (AKIA + 16 ký tự)
    fake_key    = "AKIASIMULATEDKEY0001"
    fake_secret = "SimulatedSecretKey/ABCDEFGHIJ1234567890+sim"

    # Lưu vào generated_credentials.txt
    creds_path = Path(__file__).parent / "generated_credentials.txt"
    creds_path.write_text(
        f"# Generated by aws_setup.py --sim on {datetime.now().strftime('%Y-%m-%d %H:%M')}\n"
        f"# IAM User : {IAM_USER}\n"
        f"# NOTE     : Simulated credentials — for local lab only\n\n"
        f"[{IAM_USER}]\n"
        f"aws_access_key_id     = {fake_key}\n"
        f"aws_secret_access_key = {fake_secret}\n"
        f"region                = {REGION}\n"
    )

    # Cũng đặt vào simulated-fs để giả lập file bị lộ trên web server
    leaked_path = Path(__file__).parent.parent / \
                  "vulnerable-app" / "simulated-fs" / "home" / "ubuntu" / ".aws" / "credentials"
    leaked_path.parent.mkdir(parents=True, exist_ok=True)
    leaked_path.write_text(
        f"[default]\n"
        f"aws_access_key_id     = {fake_key}\n"
        f"aws_secret_access_key = {fake_secret}\n"
        f"region                = {REGION}\n\n"
        f"# NOTE (left by dev): Temporary credentials for svc-backup-agent.\n"
        f"# TODO: Rotate these after the migration sprint — Q3 2024\n"
        f"# DO NOT commit this file. (Oops — already did on 2024-08-15)\n"
    )

    print(f"    ✓ Access Key ID    : {fake_key}")
    print(f"    ✓ Credentials file : {creds_path}")
    print(f"    ✓ Leaked copy      : {leaked_path}")

    # ── Summary ───────────────────────────────────────────────
    print("\n" + "═" * 60)
    print("✅ LAB SETUP COMPLETE (Simulation Mode)")
    print("═" * 60)
    print(f"\n  Simulated S3 Bucket:")
    print(f"    {bucket_dir}")
    for f in bucket_dir.glob("*.csv"):
        print(f"    └─ {f.name}  ({f.stat().st_size} bytes)")

    print(f"\n  Simulated IAM User : {IAM_USER}")
