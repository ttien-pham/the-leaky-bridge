    group.add_argument('--teardown', action='store_true', help='Destroy lab')
    parser.add_argument('--region',  default=REGION)
    parser.add_argument('--local',   action='store_true', help='Use LocalStack')
    parser.add_argument('--sim',     action='store_true', help='Pure local simulation (recommended)')
    args = parser.parse_args()

    if args.sim:
        if args.setup:
            setup_sim()
        else:
            teardown_sim()
    elif args.setup:
        setup_lab(args.region, args.local)
    else:
        teardown_lab(args.region, args.local)
