def teardown_sim():
    """Xóa toàn bộ thư mục simulated-cloud."""
    banner()
    print("⚠  TEARING DOWN Simulation Lab...\n")

    if SIM_ROOT.exists():
        shutil.rmtree(SIM_ROOT)
        print(f"    ✓ Deleted: {SIM_ROOT}")
    else:
        print(f"    ⚠ Không tìm thấy {SIM_ROOT} — đã xóa rồi?")

    creds_path = Path(__file__).parent / "generated_credentials.txt"
    if creds_path.exists():
        creds_path.unlink()
        print(f"    ✓ Deleted: {creds_path}")

    print("\n✅ TEARDOWN COMPLETE\n")


